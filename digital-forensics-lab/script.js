function setupNotebook() {
  const notebookBtn = document.getElementById("btn-open-notebook");
  const textarea = document.getElementById("notebook-content");

  if (notebookBtn) {
    notebookBtn.addEventListener("click", () => {
      if (textarea) textarea.value = appState.investigatorNotes || "";
      openModal("modal-notebook");
    });
  }

  if (textarea) {
    let timeoutId;
    textarea.addEventListener("input", (e) => {
      appState.investigatorNotes = e.target.value;
      const status = document.getElementById("notebook-save-status");
      if (status) status.textContent = "Saving...";
      clearTimeout(timeoutId);
      timeoutId = setTimeout(() => {
        saveState();
        if (status) status.textContent = "Saved to browser ✓";
      }, 600);
    });
  }
}

