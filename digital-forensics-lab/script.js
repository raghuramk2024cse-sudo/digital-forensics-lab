function renderChallengeView() {
  const activeCase = getActiveCase();
  const progress = getActiveProgress();
  const container = document.getElementById("challenge-questions-container");
  if (!container) return;

  const titleEl = document.getElementById("challenge-case-title");
  if (titleEl) titleEl.textContent = `${activeCase.id}: Case Examination`;

  container.innerHTML = "";

  const isSubmitted = progress.challengeSubmitted || false;
  const userAnswers = progress.challengeAnswers || {};

  const scoreCard = document.getElementById("challenge-score-card");
  if (scoreCard) {
    if (isSubmitted) {
      scoreCard.classList.add("show");
      const numEl = document.getElementById("challenge-score-number");
      const gradeEl = document.getElementById("challenge-score-grade");
      if (numEl) numEl.textContent = progress.challengeScore;
      if (gradeEl) {
        if (progress.challengeScore >= 90) gradeEl.innerHTML = `<span style="color:var(--neon-green);">Exemplary Examiner</span> - Flawless evidence-based reasoning.`;
        else if (progress.challengeScore >= 70) gradeEl.innerHTML = `<span style="color:var(--neon-cyan);">Proficient Detective</span> - Sound reasoning with minor oversights.`;
        else gradeEl.innerHTML = `<span style="color:var(--neon-amber);">Needs Revision</span> - Make sure not to jump to conclusions before evidence is checked.`;
      }
    } else {
      scoreCard.classList.remove("show");
    }
  }

  activeCase.challenge.forEach((q, qIndex) => {
    const card = document.createElement("div");
    card.className = "challenge-card";

    let optionsMarkup = "";

    if (q.type === "single") {
      const selectedIndex = userAnswers[q.id];

      q.options.forEach((optText, oIdx) => {
        let labelClass = "";
        let isChecked = selectedIndex === oIdx;

        if (isSubmitted) {
          if (oIdx === q.correctIndex) {
            labelClass = "is-correct";
          } else if (isChecked && oIdx !== q.correctIndex) {
            labelClass = "is-incorrect";
          }
        } else if (isChecked) {
          labelClass = "is-selected";
        }

        optionsMarkup += `
          <label class="challenge-option-label ${labelClass}">
            <input type="radio" name="challenge_${q.id}" value="${oIdx}" ${isChecked ? 'checked' : ''} ${isSubmitted ? 'disabled' : ''} onchange="onSelectChallengeOption('${q.id}', ${oIdx})">
            <div>${optText}</div>
          </label>
        `;
      });
    } else if (q.type === "multi") {
      const selectedIndices = userAnswers[q.id] || [];

      q.options.forEach((optText, oIdx) => {
        let labelClass = "";
        let isChecked = selectedIndices.includes(oIdx);

        if (isSubmitted) {
          if (q.correctIndices.includes(oIdx)) {
            labelClass = "is-correct";
          } else if (isChecked && !q.correctIndices.includes(oIdx)) {
            labelClass = "is-incorrect";
          }
        } else if (isChecked) {
          labelClass = "is-selected";
        }

        optionsMarkup += `
          <label class="challenge-option-label ${labelClass}">
            <input type="checkbox" name="challenge_${q.id}" value="${oIdx}" ${isChecked ? 'checked' : ''} ${isSubmitted ? 'disabled' : ''} onchange="onToggleChallengeCheckbox('${q.id}', ${oIdx})">
            <div>${optText}</div>
          </label>
        `;
      });
    }

    card.innerHTML = `
      <div class="challenge-question-header">
        <div>
          <span class="question-num-tag">QUESTION ${qIndex + 1} OF ${activeCase.challenge.length} &bull; ${q.type === 'multi' ? 'SELECT MULTIPLE' : 'SINGLE CHOICE'}</span>
          <h4 class="question-title">${q.prompt}</h4>
        </div>
      </div>

      <div class="challenge-options-list">
        ${optionsMarkup}
      </div>

      <div class="question-explanation-box ${isSubmitted ? 'show' : ''}">
        <div class="explanation-title">
          <svg viewBox="0 0 24 24" width="16" height="16" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"/><path d="M12 16v-4M12 8h.01"/></svg>
          Forensic Explanation:
        </div>
        <div>${q.explanation}</div>
      </div>
    `;

    container.appendChild(card);
  });

  const submitBtn = document.getElementById("btn-submit-challenge");
  if (submitBtn) {
    if (isSubmitted) {
      submitBtn.textContent = "Retake Case Challenge";
      submitBtn.classList.remove("btn-primary");
      submitBtn.classList.add("btn-secondary");
    } else {
      submitBtn.textContent = "Submit Answers & Score Exam";
      submitBtn.classList.add("btn-primary");
      submitBtn.classList.remove("btn-secondary");
    }
  }
}

function onSelectChallengeOption(qId, optionIndex) {
  const progress = getActiveProgress();
  if (!progress.challengeAnswers) progress.challengeAnswers = {};
  progress.challengeAnswers[qId] = optionIndex;
  saveState();
  renderChallengeView();
}

function onToggleChallengeCheckbox(qId, optionIndex) {
  const progress = getActiveProgress();
  if (!progress.challengeAnswers) progress.challengeAnswers = {};
  if (!Array.isArray(progress.challengeAnswers[qId])) {
    progress.challengeAnswers[qId] = [];
  }

  const arr = progress.challengeAnswers[qId];
  const idx = arr.indexOf(optionIndex);
  if (idx > -1) arr.splice(idx, 1);
  else arr.push(optionIndex);

  saveState();
  renderChallengeView();
}

function submitInvestigationChallenge() {
  const activeCase = getActiveCase();
  const progress = getActiveProgress();

  if (progress.challengeSubmitted) {
    progress.challengeSubmitted = false;
    saveState();
    showToast("Challenge unlocked for re-testing.", "info");
    renderChallengeView();
    return;
  }

  const userAnswers = progress.challengeAnswers || {};
  const unanswered = [];
  activeCase.challenge.forEach((q, i) => {
    const val = userAnswers[q.id];
    if (val === undefined || (Array.isArray(val) && val.length === 0)) {
      unanswered.push(i + 1);
    }
  });

  if (unanswered.length > 0) {
    showToast(`Please answer all questions first! Missing: Question ${unanswered.join(", ")}`, "warning");
    return;
  }

  let correctPoints = 0;
  activeCase.challenge.forEach(q => {
    const ans = userAnswers[q.id];
    if (q.type === "single") {
      if (ans === q.correctIndex) correctPoints += 1;
    } else if (q.type === "multi") {
      const correctArr = [...q.correctIndices].sort();
      const userArr = Array.isArray(ans) ? [...ans].sort() : [];
      if (JSON.stringify(correctArr) === JSON.stringify(userArr)) {
        correctPoints += 1;
      }
    }
  });

  const finalScore = Math.round((correctPoints / activeCase.challenge.length) * 100);

  progress.challengeSubmitted = true;
  progress.challengeScore = finalScore;
  progress.completed = true;

  saveState();
  updateGlobalStats();
  updateStepperUI();
  renderChallengeView();

  showToast(`Exam completed! Score: ${finalScore}%`, finalScore >= 70 ? "success" : "info");
}

