function exportReportAsText() {
  const activeCase = getActiveCase();
  const progress = getActiveProgress();
  const now = new Date().toUTCString();
  const examinerName = appState.investigatorName || "Alex Rivera";
  const rank = getInvestigatorRank();

  const text = `
================================================================================
DIGITAL FORENSICS INCIDENT INVESTIGATION REPORT
================================================================================
Case ID:         ${activeCase.id}
Incident Title:  ${activeCase.title}
Difficulty:      ${activeCase.difficulty}
Date Generated:  ${now}
Examiner:        ${examinerName} (${rank.title})
Assessment Score:${progress.challengeSubmitted ? progress.challengeScore + "%" : "PENDING"}

1.0 INCIDENT SCENARIO
--------------------------------------------------------------------------------
${activeCase.scenario}

Objective:
${activeCase.objective}

2.0 EXAMINED FORENSIC ARTIFACTS (${(progress.reviewedEvidence || []).length} / ${activeCase.evidence.length})
--------------------------------------------------------------------------------
${activeCase.evidence.map(e => `[${e.id}] ${e.timestamp} | ${e.type.toUpperCase()} | ${e.source}
Summary: ${e.summary}
Plain English: ${e.plainEnglish}
SHA-256: ${e.hash}
Details: ${e.details}
`).join("\n")}

3.0 SUSPICIOUS PATTERNS & HEURISTICS
--------------------------------------------------------------------------------
${activeCase.suspiciousRules.map(r => `* ${r.ruleId}: ${r.name} [Severity: ${r.severity.toUpperCase()}]
  Detected Event: ${r.detectedEvent}
  Reason:         ${r.reason}
  Observed Fact:  ${r.observedFact}
  Forensic Nuance: ${r.hypothesis}
  Next Steps:     ${r.recommendedStep}
`).join("\n")}

4.0 INVESTIGATOR CONCLUSION
--------------------------------------------------------------------------------
The evidence demonstrates unauthorized activity using valid credentials from
unauthorized endpoints. In keeping with forensic standards, observed facts are
separated from unverified assumptions regarding perpetrator identity.

================================================================================
END OF REPORT // DIGITAL FORENSICS LAB
================================================================================
`.trim();

  const blob = new Blob([text], { type: "text/plain;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `Forensic_Report_${activeCase.id}.txt`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);

  showToast("Report exported as text file!", "success");
}

