document.addEventListener("DOMContentLoaded", () => {
  initApp();
});

function initApp() {
  setupNavigation();
  setupGlobalControls();
  setupModalListeners();
  setupEvidenceViewer();
  setupTimelineView();
  setupFindingsView();
  setupChallengeView();
  setupReportView();
  setupNotebook();

  // Support URL hash or ?view= parameter for direct view loading
  const urlParams = new URLSearchParams(window.location.search);
  const requestedView = urlParams.get("view") || (window.location.hash ? window.location.hash.replace("#", "") : null);
  if (requestedView) {
    const targetId = requestedView.startsWith("view-") ? requestedView : `view-${requestedView}`;
    if (document.getElementById(targetId)) {
      navigateTo(targetId);
    } else {
      renderCurrentView();
    }
  } else {
    renderCurrentView();
  }
  updateGlobalStats();
  updateInvestigatorProfileUI();
}

let currentViewId = "view-dashboard";

function navigateTo(viewId) {
  currentViewId = viewId;
  
  // Update sidebar active class
  document.querySelectorAll(".nav-item").forEach(item => {
    if (item.getAttribute("data-view") === viewId) {
      item.classList.add("active");
    } else {
      item.classList.remove("active");
    }
  });

  // Switch visible section
  document.querySelectorAll(".view-section").forEach(sec => {
    if (sec.id === viewId) {
      sec.classList.add("active-view");
    } else {
      sec.classList.remove("active-view");
    }
  });

  renderCurrentView();
  updateStepperUI();
  window.scrollTo({ top: 0, behavior: "smooth" });
  closeMobileSidebar();
}

function renderCurrentView() {
  updateHeaderActiveCaseBanner();
  updateGlobalStats();
  updateInvestigatorProfileUI();

  switch (currentViewId) {
    case "view-dashboard":
      renderDashboard();
      break;
    case "view-cases":
      renderCaseSelection();
      break;
    case "view-evidence":
      renderEvidenceViewer();
      break;
    case "view-timeline":
      renderTimelineView();
      break;
    case "view-findings":
      renderFindingsView();
      break;
    case "view-challenge":
      renderChallengeView();
      break;
    case "view-report":
      renderReportView();
      break;
  }
}

function updateStepperUI() {
  const stepperContainer = document.getElementById("active-case-stepper");
  if (!stepperContainer) return;

  const caseViews = ["view-evidence", "view-timeline", "view-findings", "view-challenge", "view-report"];
  if (!caseViews.includes(currentViewId)) {
    stepperContainer.style.display = "none";
    return;
  }

  stepperContainer.style.display = "flex";
  const progress = getActiveProgress();

  document.querySelectorAll(".stepper-step").forEach(btn => {
    const target = btn.getAttribute("data-step-view");
    btn.classList.remove("active", "completed");

    if (target === currentViewId) {
      btn.classList.add("active");
    }

    if (target === "view-evidence" && progress.reviewedEvidence.length >= 3) {
      btn.classList.add("completed");
    }
    if (target === "view-challenge" && progress.challengeSubmitted) {
      btn.classList.add("completed");
    }
    if (target === "view-report" && progress.completed) {
      btn.classList.add("completed");
    }
  });
}

function setupNavigation() {
  document.querySelectorAll(".nav-item").forEach(item => {
    item.addEventListener("click", (e) => {
      e.preventDefault();
      const targetView = item.getAttribute("data-view");
      if (targetView) navigateTo(targetView);
    });
  });

  document.querySelectorAll(".stepper-step").forEach(stepBtn => {
    stepBtn.addEventListener("click", () => {
      const target = stepBtn.getAttribute("data-step-view");
      if (target) navigateTo(target);
    });
  });

  const toggleBtn = document.getElementById("btn-mobile-sidebar");
  const closeBtn = document.getElementById("btn-close-sidebar");
  const sidebar = document.getElementById("app-sidebar");

  if (toggleBtn) {
    toggleBtn.addEventListener("click", () => {
      sidebar.classList.toggle("mobile-open");
    });
  }
  if (closeBtn) {
    closeBtn.addEventListener("click", closeMobileSidebar);
  }
}

function closeMobileSidebar() {
  const sidebar = document.getElementById("app-sidebar");
  if (sidebar) sidebar.classList.remove("mobile-open");
}

function setupGlobalControls() {
  // Reset Progress Button
  const resetBtn = document.getElementById("btn-reset-progress");
  if (resetBtn) {
    resetBtn.addEventListener("click", () => openModal("modal-reset-confirm"));
  }

  const confirmResetBtn = document.getElementById("btn-confirm-reset");
  if (confirmResetBtn) {
    confirmResetBtn.addEventListener("click", () => {
      localStorage.removeItem(STORAGE_KEY);
      appState = JSON.parse(JSON.stringify(defaultState));
      saveState();
      closeModal("modal-reset-confirm");
      showToast("All progress reset! Ready for a fresh start.", "info");
      renderCurrentView();
    });
  }

  // Guide / Primer Modal
  const primerBtn = document.getElementById("btn-open-primer");
  if (primerBtn) {
    primerBtn.addEventListener("click", () => openModal("modal-primer"));
  }

  // Mentor Guidance
  const mentorBtn = document.getElementById("btn-open-mentor");
  if (mentorBtn) {
    mentorBtn.addEventListener("click", () => {
      const activeCase = getActiveCase();
      const tipText = document.getElementById("mentor-tip-content");
      if (tipText) tipText.textContent = activeCase.mentorTip;
      openModal("modal-mentor");
    });
  }

  // Profile Edit
  const profilePill = document.getElementById("header-profile-pill");
  if (profilePill) {
    profilePill.addEventListener("click", () => {
      const nameInput = document.getElementById("input-investigator-name");
      if (nameInput) nameInput.value = appState.investigatorName || "Alex Rivera";
      openModal("modal-profile");
    });
  }

  const saveProfileBtn = document.getElementById("btn-save-profile");
  if (saveProfileBtn) {
    saveProfileBtn.addEventListener("click", () => {
      const nameInput = document.getElementById("input-investigator-name");
      if (nameInput && nameInput.value.trim()) {
        appState.investigatorName = nameInput.value.trim();
        saveState();
        updateInvestigatorProfileUI();
        closeModal("modal-profile");
        showToast(`Profile updated! Welcome, ${appState.investigatorName}.`, "success");
      }
    });
  }
}

function updateInvestigatorProfileUI() {
  const rank = getInvestigatorRank();
  const nameEl = document.getElementById("header-profile-name");
  const rankEl = document.getElementById("header-profile-rank");
  const avatarEl = document.getElementById("header-profile-avatar");

  if (nameEl) nameEl.textContent = appState.investigatorName || "Investigator";
  if (rankEl) rankEl.textContent = rank.title;
  if (avatarEl) {
    const initials = (appState.investigatorName || "A").substring(0, 1).toUpperCase();
    avatarEl.textContent = initials;
  }

  // Welcome banner on dashboard
  const welcomeName = document.getElementById("welcome-investigator-name");
  const welcomeRank = document.getElementById("welcome-investigator-rank");
  if (welcomeName) welcomeName.textContent = appState.investigatorName || "Investigator";
  if (welcomeRank) welcomeRank.textContent = rank.title;
}

function updateHeaderActiveCaseBanner() {
  const activeCase = getActiveCase();
  const caseTag = document.getElementById("header-case-id");
  const caseName = document.getElementById("header-case-name");
  
  if (caseTag) caseTag.textContent = activeCase.id;
  if (caseName) caseName.textContent = activeCase.title;
}

function updateGlobalStats() {
  let completedCount = 0;
  let totalScore = 0;
  let totalEvidenceExamined = 0;

  FORENSIC_CASES.forEach(c => {
    const prog = appState.casesProgress[c.id];
    if (prog) {
      if (prog.completed) completedCount++;
      if (prog.challengeSubmitted) totalScore += (prog.challengeScore || 0);
      totalEvidenceExamined += (prog.reviewedEvidence ? prog.reviewedEvidence.length : 0);
    }
  });

  const avgScore = completedCount > 0 ? Math.round(totalScore / completedCount) : (totalScore > 0 ? totalScore : 0);

  const statCompleted = document.getElementById("stat-header-completed");
  const statScore = document.getElementById("stat-header-score");
  if (statCompleted) statCompleted.textContent = `${completedCount}/3`;
  if (statScore) statScore.textContent = `${avgScore} pts`;

  const elTotalCases = document.getElementById("dash-total-cases");
  const elCompleted = document.getElementById("dash-completed-cases");
  const elEvidence = document.getElementById("dash-evidence-examined");
  const elAvgScore = document.getElementById("dash-avg-score");

  if (elTotalCases) elTotalCases.textContent = FORENSIC_CASES.length;
  if (elCompleted) elCompleted.textContent = completedCount;
  if (elEvidence) elEvidence.textContent = totalEvidenceExamined;
  if (elAvgScore) elAvgScore.textContent = `${avgScore}%`;
}

