let appState = loadState();

function loadState() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return JSON.parse(JSON.stringify(defaultState));
    const parsed = JSON.parse(raw);
    if (!parsed.investigatorName) parsed.investigatorName = "Alex Rivera";
    if (parsed.investigatorNotes === undefined) parsed.investigatorNotes = "";
    if (!parsed.casesProgress) parsed.casesProgress = {};
    FORENSIC_CASES.forEach(c => {
      if (!parsed.casesProgress[c.id]) {
        parsed.casesProgress[c.id] = {
          reviewedEvidence: [],
          flaggedEvidence: [],
          challengeAnswers: {},
          challengeSubmitted: false,
          challengeScore: 0,
          completed: false
        };
      }
    });
    return parsed;
  } catch (e) {
    console.error("Error loading state from localStorage:", e);
    return JSON.parse(JSON.stringify(defaultState));
  }
}

function saveState() {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(appState));
  } catch (e) {
    console.error("Error saving state to localStorage:", e);
  }
}

function getActiveCase() {
  return FORENSIC_CASES.find(c => c.id === appState.activeCaseId) || FORENSIC_CASES[0];
}

function getActiveProgress() {
  const caseId = appState.activeCaseId;
  if (!appState.casesProgress[caseId]) {
    appState.casesProgress[caseId] = {
      reviewedEvidence: [],
      flaggedEvidence: [],
      challengeAnswers: {},
      challengeSubmitted: false,
      challengeScore: 0,
      completed: false
    };
  }
  return appState.casesProgress[caseId];
}

// Compute rank based on cases completed
function getInvestigatorRank() {
  let completed = 0;
  FORENSIC_CASES.forEach(c => {
    if (appState.casesProgress[c.id] && appState.casesProgress[c.id].completed) {
      completed++;
    }
  });

  if (completed >= 3) return { title: "Chief Forensic Examiner", level: "Level 4 (Master)" };
  if (completed === 2) return { title: "Lead Incident Responder", level: "Level 3 (Senior)" };
  if (completed === 1) return { title: "Forensic Detective", level: "Level 2 (Associate)" };
  return { title: "Junior Analyst", level: "Level 1 (Apprentice)" };
}

